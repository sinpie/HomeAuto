"""Pack the UI assets (background, icons, fonts) into assets/assets.bin.

The firmware memory-maps this blob from the "ffat" flash partition at boot
(HomePanel/assets.cpp), so large images and fonts are never compiled.
tools/upload_p4.py writes the blob only when it changed.

  py -3 tools/assets_pack.py      # re-pack (also run by make_font.py / make_assets.py)

Layout (little endian, every section 4-byte aligned):
  header  "HPA1", u32 version=1, u32 total_size, u32 section_count
  entries section_count x (u32 type, u32 offset, u32 size)
  type 1  background: u16 width, u16 height, u32 0, RGB565 pixels
  type 2  icons:      u16 icon_count, u16 size_count, u8 sizes[4], u32 offsets[icon*size_count+size], 4-bit bitmap
  type 3  font:       u16 font_id, u16 height, u32 glyph_count, glyphs (u32 code, u16 advance, u16 0, u32 offset), 4-bit bitmap
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'tools'))
ASSETS = ROOT/'assets'
BACKGROUND = ASSETS/'background.png'
OUTPUT = ASSETS/'assets.bin'
HEADER = ROOT/'HomePanel'/'assets_data.h'
W, H = 1024, 600
MAGIC, VERSION = b'HPA1', 1


def section_background():
    from PIL import Image
    import make_assets
    image = Image.open(BACKGROUND).convert('RGB')
    if image.size != (W, H):
        raise SystemExit(f'{BACKGROUND} must be {W}x{H}, got {image.size}')
    pixels = make_assets.to_rgb565(image)
    return struct.pack('<HHI', W, H, 0) + struct.pack(f'<{len(pixels)}H', *pixels)


def section_icons():
    import make_assets
    preview = ROOT/'tools'/'preview'
    preview.mkdir(exist_ok=True)
    bitmap, table = make_assets.render_icons(preview/'icons.png')
    sizes = list(make_assets.ICON_SIZES)
    head = struct.pack('<HH4B', len(table), len(sizes), *(sizes + [0] * (4 - len(sizes))))
    offsets = [o for row in table for o in row]
    return head + struct.pack(f'<{len(offsets)}I', *offsets) + bitmap


def section_font(font_id, height, glyphs, bitmap):
    table = b''.join(struct.pack('<IHxxI', code, advance, offset) for code, advance, offset in glyphs)
    return struct.pack('<HHI', font_id, height, len(glyphs)) + table + bitmap


def write_header():
    """Icon ids and sizes are compile-time constants; only this small header is code."""
    import make_assets
    names = [name for name, _ in make_assets.ICONS]
    text = '\n'.join([
        '#pragma once',
        '// Generated by tools/assets_pack.py. Do not edit. Icon images live in assets/assets.bin.',
        '#include <stdint.h>',
        'enum IconId { ' + ', '.join(f'ICON_{n}' for n in names) + ', ICON_COUNT };',
        f'constexpr int ICON_SIZE_COUNT = {len(make_assets.ICON_SIZES)};',
        'static const uint8_t ICON_SIZES[ICON_SIZE_COUNT] = {' + ','.join(map(str, make_assets.ICON_SIZES)) + '};',
        '#include "assets.h"',
        ''])
    if not HEADER.exists() or HEADER.read_text(encoding='utf-8') != text:
        HEADER.write_text(text, encoding='utf-8')  # unchanged header -> no recompile


def pack():
    import make_font
    sections = [(1, section_background()), (2, section_icons())]
    for font_id, (height, glyphs, bitmap) in enumerate(make_font.build_all()):
        sections.append((3, section_font(font_id, height, glyphs, bitmap)))
    offset = 16 + 12 * len(sections)
    entries, body = [], bytearray()
    for kind, data in sections:
        offset = (offset + 3) & ~3
        pad = offset - (16 + 12 * len(sections) + len(body))
        body += b'\0' * pad
        entries.append(struct.pack('<III', kind, offset, len(data)))
        body += data
        offset += len(data)
    total = 16 + 12 * len(sections) + len(body)
    blob = MAGIC + struct.pack('<III', VERSION, total, len(sections)) + b''.join(entries) + body
    ASSETS.mkdir(exist_ok=True)
    OUTPUT.write_bytes(blob)
    write_header()
    print(f'{OUTPUT.relative_to(ROOT)}: {total/1024:.0f} KiB, {len(sections)} sections')
    return OUTPUT


if __name__ == '__main__':
    pack()
