"""Rasterize the UI character set into anti-aliased 4-bit bitmap fonts.

Source font: Noto Sans KR (SIL Open Font License 1.1), installed with Windows.
Only the glyphs used by HomePanel/app.cpp are generated; the font file itself
is not redistributed. Run after changing any UI text:  py -3 tools/make_font.py
"""
import math
import re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = r'C:\Windows\Fonts\NotoSansKR-VF.ttf'
ASCII = ''.join(chr(c) for c in range(32, 127))
DIGITS = '0123456789.-°B% '
# name, pixel size, weight, character set ('ui' = ASCII + every literal in app.cpp)
FONTS = [
    ('CAPTION', 19, 400, 'ui'),
    ('BODY', 23, 500, 'ui'),
    ('TITLE', 30, 700, 'ui'),
    ('DISPLAY', 60, 600, DIGITS),
]


def ui_chars():
    source = (ROOT/'HomePanel'/'app.cpp').read_text(encoding='utf-8')
    literals = ''.join(re.findall(r'"([^"\n]*)"', source))
    return sorted(set(ASCII + literals + '°·'))


def load(size, weight):
    font = ImageFont.truetype(SOURCE, size)
    font.set_variation_by_axes([weight])
    return font


def build(name, size, weight, charset):
    font = load(size, weight)
    chars = ui_chars() if charset == 'ui' else sorted(set(charset))
    # One tight line box per font: union of the ink of every glyph.
    top = min(font.getbbox(ch)[1] for ch in chars if ch.strip())
    bottom = max(font.getbbox(ch)[3] for ch in chars if ch.strip())
    height = bottom - top
    glyphs, bitmap = [], bytearray()
    for ch in chars:
        advance = max(1, math.ceil(font.getlength(ch)))
        image = Image.new('L', (advance, height))
        ImageDraw.Draw(image).text((0, -top), ch, font=font, fill=255)
        offset = len(bitmap)
        for y in range(height):
            row = [image.getpixel((x, y)) * 15 // 255 for x in range(advance)]
            if len(row) % 2:
                row.append(0)
            bitmap.extend((row[i] << 4) | row[i+1] for i in range(0, len(row), 2))
        glyphs.append((ord(ch), advance, offset))
    lines = [f'static const uint8_t FONT_{name}_BITMAP[] = {{']
    for i in range(0, len(bitmap), 32):
        lines.append(','.join(map(str, bitmap[i:i+32])) + ',')
    lines.append('};')
    lines.append(f'static const Glyph FONT_{name}_GLYPHS[] = {{')
    lines += [f'{{{code},{advance},{offset}}},' for code, advance, offset in glyphs]
    lines.append('};')
    lines.append(f'static const Font FONT_{name} = {{FONT_{name}_GLYPHS, {len(glyphs)}, {height}, FONT_{name}_BITMAP}};')
    return lines, len(glyphs), height, len(bitmap)


def main():
    out = ['#pragma once', '// Generated by tools/make_font.py from Noto Sans KR (OFL-1.1). Do not edit.',
           '#include <stdint.h>',
           'struct Glyph { uint32_t code; uint16_t advance; uint32_t offset; };  // 4-bit alpha, rows padded to bytes',
           'struct Font { const Glyph* glyphs; uint16_t count; uint8_t height; const uint8_t* bitmap; };']
    for spec in FONTS:
        lines, count, height, size = build(*spec)
        out += lines
        print(f'{spec[0]:8} {count:4} glyphs  height {height:3}px  {size/1024:6.1f} KiB')
    (ROOT/'HomePanel'/'font_data.h').write_text('\n'.join(out) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
